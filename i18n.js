// Suffix keys resolved per-language (e.g. "login.legal" has an explicit
// English variant "login.legal.en"): prefer the language-specific entry when
// it exists.
function lookup(key, l) {
  const dict = DICT[l] || DICT.zh;
  if (dict[key + "." + l] !== undefined) return dict[key + "." + l];
  if (dict[key] !== undefined) return dict[key];
  const other = DICT[l === "zh" ? "en" : "zh"];
  if (other && other[key] !== undefined) return other[key];
  return key;
}

/// t("key") or t("key", {n: 3}) — {placeholder} interpolation keeps params.
export function t(key, params) {
  let s = lookup(key, currentLang);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split("{" + k + "}").join(String(v));
    }
  }
  return s;
}

/// Apply static translations to [data-i18n] (textContent),
/// [data-i18n-aria] (aria-label) and [data-i18n-html] (innerHTML) nodes,
/// plus <html lang> and the document title.
export function applyStaticI18n(root = document) {
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
  root.querySelectorAll(".brand-english").forEach(el => { el.hidden = currentLang === "en"; });
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder)); });
  root.querySelectorAll("[data-i18n-href]").forEach((el) => { el.setAttribute("href", t(el.dataset.i18nHref)); });
  const title = root.querySelector("head title");
  if (title) title.textContent = t("doc.title");
}
