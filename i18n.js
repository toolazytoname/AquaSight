// Central bilingual dictionary + t() for the web app.
// Language resolution: localStorage "aquasight-language" (zh|en) → browser
// language (zh* → zh, everything else → en). Switching is a local UI
// preference only: it never touches account data or subscriptions.

const LANG_KEY = "aquasight-language";
export const LANGS = ["zh", "en"];

function readStoredLang() {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "zh" || v === "en") return v;
  } catch {}
  return "";
}

let currentLang = readStoredLang() || (typeof navigator !== "undefined" && navigator.language && navigator.language.startsWith("zh") ? "zh" : "en");

const listeners = new Set();
export function onLanguageChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function lang() { return currentLang; }
export function isZh() { return currentLang === "zh"; }

export function setLang(next) {
  if (next !== "zh" && next !== "en") return false;
  if (next === currentLang) return true;
  currentLang = next;
  try { localStorage.setItem(LANG_KEY, next); } catch {}
  for (const fn of listeners) { try { fn(next); } catch {} }
  return true;
}

