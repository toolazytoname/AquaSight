import { articleId } from "../identity.js";
import { isGithubJunk } from "./github.js";

/**
 * Curated "maintained quality repos" feed via the GitHub Search API
 * (https://docs.github.com/en/rest/search/search#search-repositories).
 *
 * Strategy: a small fixed set of topic queries, run SEQUENTIALLY (the Search
 * API has its own, much lower rate limit — 10 req/min unauthenticated — so
 * unbounded parallelism is never allowed), each sorted by `updated` so the
 * result is "recently maintained repos above a star floor", not another
 * all-time stars leaderboard. Quality/diversity rules (per-owner,
 * per-language caps, minimum description) keep one owner or one language from
 * monopolizing the feed.
 *
 * Works keyless; an existing GITHUB_TOKEN (no extra scopes) is used if set.
 * `incomplete_results: true` (or a non-array items payload) is surfaced as a
 * source warning instead of being reported as fully healthy.
 */

const API = "https://api.github.com/search/repositories";

// Request budget: at most MAX_REQUESTS sequential search calls per collect.
export const MAX_REQUESTS = 3;
export const PER_PAGE = 12;

export const QUERY_BUCKETS = [
  { topic: "ai", minStars: 1000, pushedWithinDays: 60 },
  { topic: "developer-tools", minStars: 3000, pushedWithinDays: 90 },
  { topic: "web", minStars: 5000, pushedWithinDays: 90 },
];

export const OWNER_CAP = 2;
export const LANGUAGE_CAP = 5;
export const OUTPUT_LIMIT = 12;
export const MIN_DESC_LEN = 8;

/**
 * Auto-updated registries/mirrors dominate `sort=updated` heads (e.g.
 * crates.io-index): "recently pushed" but not maintained projects a reader
 * would browse. The rules are deliberately NARROW — an ordinary project
 * legitimately named e.g. "search-index" with a real product description is
 * NOT excluded; only exact boring names, known registry-index names, or
 * descriptions that say the content is auto-generated/mirrored.
 */
export const AUTO_NAME_RE =
  /^(index|mirror|mirrors|snapshots?|releases?|archive|archives|changelog)(\.git)?$/i;
export const AUTO_REGISTRY_RE =
  /(crates\.io-index|cargo-index|registry-index|package-index|npm-mirror|pypi-mirror)(\.git)?$/i;
export const AUTO_DESC_RE =
  /automatically (updated|generated)|auto[- ]generated|mirror(s)? of|crate index|package (index|registry)|generated by (ci|bot|github actions)/i;

function isAutoUpdateRepo(repo) {
  const name = String(repo.name || String(repo.full_name || "").split("/").pop() || "");
  if (AUTO_NAME_RE.test(name) || AUTO_REGISTRY_RE.test(name)) return true;
  return AUTO_DESC_RE.test(String(repo.description || ""));
}

function ymd(d) {
  return d.toISOString().slice(0, 10);
}

export function searchUrl(bucket, now = new Date()) {
  const pushed = new Date(now.getTime() - bucket.pushedWithinDays * 86400000);
  const q = [
    "topic:" + bucket.topic,
    "stars:>=" + bucket.minStars,
    "pushed:>" + ymd(pushed),
    "fork:false",
    "archived:false",
  ].join(" ");
  return (
    API +
    "?q=" +
    encodeURIComponent(q) +
    "&sort=updated&order=desc&per_page=" +
    PER_PAGE
  );
}

export function repoSignal(repo, bucket) {
  // Verifiable, rule-based selection signal. Never an invented AI judgment.
  const bits = ["近 " + bucket.pushedWithinDays + " 天有提交"];
  bits.push(repo.stargazers_count + " star");
  bits.push("非 fork、未归档");
  if (bucket.topic) bits.push("topic: " + bucket.topic);
  return bits.join(" · ");
}

function githubRepoOf(repo, bucket, now) {
  const out = {
    fullName: repo.full_name,
    // Observation time (when this collector saw the repo), separate from any
    // news publication time; the latest observation wins on merge.
    observedAt: (now instanceof Date ? now : new Date(now)).toISOString(),
    signal: repoSignal(repo, bucket),
  };
  if (repo.description) out.description = String(repo.description).trim();
  if (repo.language) out.language = repo.language;
  if (Number.isFinite(repo.stargazers_count)) out.stars = repo.stargazers_count;
  if (repo.pushed_at) out.pushedAt = repo.pushed_at;
  // No license is shown as unknown by the UI; keep the field only when known.
  const spdx = repo.license && repo.license.spdx_id && repo.license.spdx_id !== "NOASSERTION"
    ? repo.license.spdx_id
    : "";
  if (spdx) out.license = spdx;
  return out;
}

function repoItem(repo, bucket, now) {
  const title = String(repo.full_name || "").trim();
  const page = repo.html_url || "https://github.com/" + title;
  if (!title) return null;
  const item = {
    title,
    url: page,
    source: "github-maintained",
    role: "opensource",
    kind: "maintained-repo",
    externalId: title,
    stars: Number(repo.stargazers_count) || undefined,
    githubRepo: githubRepoOf(repo, bucket, now),
  };
  if (repo.description) item.summary = String(repo.description).trim().slice(0, 280);
  // No publishedAt on purpose: an old, actively maintained repo is not news,
  // and pushed_at must not be presented as a release/publication date.
  item.id = articleId(item);
  item.articleId = item.id;
  return item;
}

/**
 * Eligibility re-verifies the bucket's own thresholds locally — the repo must
 * still meet minStars and be pushed within the window relative to `now`.
 * The Search API result is not blindly trusted.
 */
export function eligible(repo, bucket, now = new Date()) {
  if (!repo || typeof repo !== "object") return false;
  if (repo.fork || repo.archived || repo.disabled) return false;
  const desc = String(repo.description || "").trim();
  if (desc.length < MIN_DESC_LEN) return false;
  if (isGithubJunk(repo)) return false;
  if (isAutoUpdateRepo(repo)) return false;
  if (bucket) {
    if (!(Number(repo.stargazers_count) >= bucket.minStars)) return false;
    const pushed = Date.parse(repo.pushed_at || "");
    if (!Number.isFinite(pushed)) return false; // cannot prove recency
    const t = now instanceof Date ? now.getTime() : Date.parse(now);
    if (pushed < t - bucket.pushedWithinDays * 86400000 || pushed > t + 300000) return false;
  }
  return Boolean(repo.full_name && repo.html_url);
}

function byStarsDesc(a, b) {
  const d = (Number(b.repo.stargazers_count) || 0) - (Number(a.repo.stargazers_count) || 0);
  return d !== 0 ? d : String(a.repo.full_name).localeCompare(String(b.repo.full_name));
}

/**
 * Per-bucket quota with round-robin interleaving: flattening buckets in order
 * and truncating would let the first bucket (queried first) fill the output
 * and make the later bucket requests useless. Each bucket gets an equal
 * share of the output; owner/language caps still apply across the whole pick.
 * Within a bucket, candidates rank by stars — the query already guarantees
 * "pushed within N days", so this is "recently maintained + quality +
 * diversity", never a raw latest-push leaderboard.
 */
export function selectDiverseRepos(repos, buckets, opts = {}) {
  const ownerCap = opts.ownerCap ?? OWNER_CAP;
  const langCap = opts.languageCap ?? LANGUAGE_CAP;
  const limit = opts.limit ?? OUTPUT_LIMIT;
  const now = opts.now || new Date();
  const bucketList = buckets && buckets.length ? buckets : [null];
  const bucketQuota =
    opts.bucketQuota ?? Math.max(1, Math.ceil(limit / Math.max(1, bucketList.length)));
  const known = new Set(bucketList);
  const queues = bucketList.map((bucket) => ({
    taken: 0,
    q: (repos || [])
      .filter((e) => e.bucket === bucket)
      .filter((e) => eligible(e.repo, bucket, now))
      .sort(byStarsDesc),
  }));
  const strays = (repos || []).filter((e) => !known.has(e.bucket) && eligible(e.repo, e.bucket, now));
  if (strays.length) queues.push({ taken: 0, q: strays.sort(byStarsDesc) });
  const seen = new Set(); // unified case-insensitive full-name dedup
  const ownerCount = new Map();
  const langCount = new Map();
  const out = [];
  function tryTake(entry) {
    const repo = entry.repo;
    const key = String(repo.full_name).toLowerCase();
    if (seen.has(key)) return false;
    const owner = key.split("/")[0];
    const lang = String(repo.language || "").toLowerCase() || "unknown";
    if ((ownerCount.get(owner) || 0) >= ownerCap) return false;
    if ((langCount.get(lang) || 0) >= langCap) return false;
    seen.add(key);
    ownerCount.set(owner, (ownerCount.get(owner) || 0) + 1);
    langCount.set(lang, (langCount.get(lang) || 0) + 1);
    out.push(entry);
    return true;
  }
  let progress = true;
  while (out.length < limit && progress) {
    progress = false;
    for (const queue of queues) {
      if (out.length >= limit) break;
      if (queue.taken >= bucketQuota) continue;
      while (queue.q.length) {
        const entry = queue.q.shift();
        if (tryTake(entry)) {
          queue.taken += 1;
          progress = true;
          break;
        }
      }
    }
  }
  return out;
}

/**
 * @param {{fetchImpl?: Function, now?: Date, token?: string, buckets?: Array}} opts
 * @returns {Promise<Array & {warnings?: string[]}>} items; a warnings array is
 * attached when the API reported partial/abnormal results.
 */
export async function fetchGitHubMaintained(opts = {}) {
  const now = opts.now || new Date();
  const fetchImpl = opts.fetchImpl || fetch;
  const token = opts.token !== undefined ? opts.token : process.env.GITHUB_TOKEN;
  const buckets = opts.buckets || QUERY_BUCKETS;
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "AquaSight/0.2",
  };
  if (token) headers.Authorization = "Bearer " + token;
  const warnings = [];
  const collected = [];
  let requests = 0;
  for (const bucket of buckets) {
    if (requests >= MAX_REQUESTS) break;
    requests += 1;
    const res = await fetchImpl(searchUrl(bucket, now), {
      headers,
      signal: AbortSignal.timeout(opts.timeoutMs ?? 12000),
    });
    if (!res.ok) {
      if (res.status === 403 || res.status === 429) {
        throw new Error("github-maintained: rate limited (HTTP " + res.status + ")");
      }
      throw new Error("github-maintained: HTTP " + res.status);
    }
    const data = await res.json().catch(() => null);
    if (!data || !Array.isArray(data.items)) {
      throw new Error("github-maintained: unexpected search payload");
    }
    if (data.incomplete_results === true) {
      warnings.push("topic:" + bucket.topic + " incomplete_results");
    }
    for (const repo of data.items) collected.push({ repo, bucket });
  }
  const items = selectDiverseRepos(collected, buckets, { now }).map(({ repo, bucket }) =>
    repoItem(repo, bucket, now)
  );
  if (!items.length) throw new Error("github-maintained: no repos passed filters");
  if (warnings.length) items.warnings = warnings;
  return items;
}
